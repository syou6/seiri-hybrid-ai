import type { AnalysisOutput } from "./types";

const KIND_LABEL: Record<string, string> = {
  chat: "チャット",
  meeting: "会議",
  email: "メール",
  memo: "メモ",
};

/** Render an analysis as clean Markdown minutes, ready to paste anywhere. */
export function toMarkdown(output: AnalysisOutput): string {
  const { triage, result, steps } = output;
  const lines: string[] = [];

  lines.push(`# ${result.title}`);
  lines.push("");
  lines.push(
    `> 種別: ${KIND_LABEL[triage.kind] ?? triage.kind} / 緊急度: ${triage.urgency} / 機密区分: ${triage.sensitivity}`,
  );
  lines.push("");
  lines.push("## 要約");
  lines.push(result.summary);
  lines.push("");

  if (result.decisions.length > 0) {
    lines.push("## 決定事項");
    for (const d of result.decisions) lines.push(`- ${d}`);
    lines.push("");
  }

  if (result.actionItems.length > 0) {
    lines.push("## アクションアイテム");
    lines.push("| やること | 担当 | 期限 | 優先度 |");
    lines.push("| --- | --- | --- | --- |");
    for (const a of result.actionItems) {
      lines.push(`| ${a.task} | ${a.owner} | ${a.due} | ${a.priority} |`);
    }
    lines.push("");
  }

  if (result.openQuestions.length > 0) {
    lines.push("## 未決事項");
    for (const q of result.openQuestions) lines.push(`- ${q}`);
    lines.push("");
  }

  if (result.risks.length > 0) {
    lines.push("## リスク・懸念");
    for (const r of result.risks) lines.push(`- ${r}`);
    lines.push("");
  }

  lines.push("---");
  lines.push("処理ルート（Firebase AI Logic ハイブリッド推論）:");
  for (const s of steps) {
    lines.push(`- ${s.step}: ${s.route} / ${s.model} / ${s.latencyMs}ms`);
  }
  lines.push("");
  lines.push("Generated by Seiri — Hybrid AI Organizer (Firebase AI Logic)");
  return lines.join("\n");
}
